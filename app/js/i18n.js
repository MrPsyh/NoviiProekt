let current = 'ru';
export function setUiLang(lang) {
  current = STRINGS[lang] ? lang : 'en';
  document.documentElement.lang = current;
}
export const uiLang = () => current;
export function t(key, vars = {}) {
  let s = STRINGS[current][key] ?? STRINGS.en[key] ?? key;
  if (typeof s === 'string') for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, v);
  return s;
}
export function defaultUiLang(targetLang) {
  if (['ru', 'uk', 'kk', 'uz'].includes(targetLang)) return 'ru';
  if (targetLang) return 'en';
  return (navigator.language || 'en').toLowerCase().startsWith('ru') ? 'ru' : 'en';
}
